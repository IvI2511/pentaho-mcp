  /** Los paquetes de pip que usa el programa (por sus imports, conexiones y lo que llama). */
  static List<String> paquetes( Programa p, Opciones o ) {
    Set<String> r = new LinkedHashSet<>();
    List<String> todo = new ArrayList<>( p.ctx.imports );
    for ( String a : p.ctx.ayudantes.values() ) {
      for ( String l : a.split( "\n" ) ) {
        todo.add( l );
      }
    }
    StringBuilder codigo = new StringBuilder();
    for ( Bloque k : p.bloques ) {
      for ( String l : k.codigo ) {
        todo.add( l );
        codigo.append( l ).append( '\n' );
      }
    }
    for ( String l : todo ) {
      Matcher m = IMPORT.matcher( l );
      if ( m.find() ) {
        String mod = m.group( 1 );
        if ( !ESTANDAR.contains( mod ) ) {
          r.add( PIP.containsKey( mod ) ? PIP.get( mod ) : mod );
        }
      }
    }
    for ( String l : preambuloConexiones( p ) ) {
      if ( l.contains( "mysql+pymysql" ) ) {
        r.add( "pymysql" );
      } else if ( l.contains( "postgresql+psycopg2" ) ) {
        r.add( "psycopg2-binary" );
      } else if ( l.contains( "mssql+pyodbc" ) ) {
        r.add( "pyodbc" );
      } else if ( l.contains( "oracle+oracledb" ) ) {
        r.add( "oracledb" );
      }
    }
    String c = codigo.toString();
    if ( c.contains( "excel(" ) || c.contains( "ExcelWriter" ) ) {
      r.add( "openpyxl" );
    }
    if ( c.contains( "read_xml(" ) || c.contains( "to_xml(" ) ) {
      r.add( "lxml" );
    }
    if ( c.contains( "parquet(" ) && p.destino() == Destino.PANDAS ) {
      r.add( "pyarrow" );
    }
    if ( o.eda ) {
      r.add( "matplotlib" );
      if ( p.destino() == Destino.PYSPARK ) {
        r.add( "pandas" );
      }
    }
    if ( r.isEmpty() ) {
      r.add( p.destino() == Destino.PYSPARK ? "pyspark" : "pandas" );
    }
    return new ArrayList<>( r );
  }

  private static List<String> preambuloConexiones( Programa p ) {
    List<String> r = new ArrayList<>();
    CtxTrad c = p.ctx;
    if ( c.pandas() ) {
      for ( DatabaseMeta db : new ArrayList<>( c.conexiones.values() ) ) {
        r.addAll( Conexiones.crear( db, c ) );
      }
    }
    return r;
  }

  static String nombreArchivo( String f ) {
    String s = f.replace( '\\', '/' );
    return s.substring( s.lastIndexOf( '/' ) + 1 );
  }

  /** Imports, SparkSession, conexiones, VARS y ayudantes (las conexiones primero: registran variables). */
  public static List<String> preambulo( Programa p ) {
    CtxTrad c = p.ctx;
    List<String> con = new ArrayList<>();
    for ( DatabaseMeta db : new ArrayList<>( c.conexiones.values() ) ) {
      con.addAll( Conexiones.crear( db, c ) );
    }
    List<String> r = new ArrayList<>( c.imports );
    r.add( "" );
    if ( c.spark() ) {
      r.add( "_builder = SparkSession.builder.appName(" + CtxTrad.lit( p.nombre ) + ")" );
      r.add( "if os.name == \"nt\":  # " + c.t( "Windows: Spark local en localhost (un nombre de equipo con _ lo rompe)",
        "Windows: local Spark on localhost (a host name with _ breaks it)",
        "Windows: Spark local em localhost (um nome de máquina com _ o quebra)" ) );
      r.add( "    _builder = _builder.config(\"spark.driver.host\", \"localhost\").config(\"spark.driver.bindAddress\", "
        + "\"127.0.0.1\")" );
      r.add( "spark = _builder.getOrCreate()" );
      r.add( "" );
    }
    r.add( "# " + c.t( "carpeta del script (o del notebook): la misma que la del .ktr",
      "folder of the script (or notebook): the same as the .ktr's", "pasta do script (ou do notebook): a mesma do .ktr" ) );
    r.add( "AQUI = os.path.dirname(os.path.abspath(__file__)) if \"__file__\" in globals() else os.getcwd()" );
    r.add( "VARS = {" );
    for ( Map.Entry<String, String> e : c.vars.entrySet() ) {
      r.add( "    " + CtxTrad.lit( e.getKey() ) + ": " + e.getValue() + "," );
    }
    r.add( "}" );
    if ( !con.isEmpty() ) {
      r.add( "" );
      r.addAll( con );
    }
    for ( String a : c.ayudantes.values() ) {
      r.add( "" );
      r.add( "" );
      for ( String l : a.split( "\n" ) ) {
        r.add( l );
      }
    }
    return r;
  }

  /** Los bloques, cada uno con su comentario de cabecera, con la sangría dada (explicaciones y notas incluidas). */
  public static String cuerpo( Programa p, String sangria ) {
    Opciones o = new Opciones();
    o.idioma = p.ctx.idioma;
    o.explicaciones = false; // como antes: sólo la explicación que trae el bloque
    return cuerpo( p, sangria, o );
  }

  /** Los bloques con las opciones: explicación (o DescribirStep) si explicaciones, notas si notas. */
  public static String cuerpo( Programa p, String sangria, Opciones o ) {
    StringBuilder b = new StringBuilder();
    int i = 0;
    for ( Bloque k : p.bloques ) {
      i++;
      b.append( sangria ).append( "# --- " ).append( i ).append( ". " ).append( k.paso ).append( " (" ).append(
        k.tipo ).append( ")" ).append( k.estado == Estado.EXACTO ? "" : " · " + estado( k.estado, o.idioma ) )
        .append( '\n' );
      String ex = o.explicaciones ? explicacion( p, k, o.idioma ) : k.explicacion;
      if ( ex != null && !ex.trim().isEmpty() ) {
        b.append( sangria ).append( "# " ).append( ex.replace( '\n', ' ' ) ).append( '\n' );
      }
      if ( o.notas || k.estado == Estado.MANUAL ) {
        for ( String n : k.notas ) {
          b.append( sangria ).append( "# " ).append( t( o.idioma, "NOTA: ", "NOTE: ", "NOTA: " ) ).append( n.replace(
            '\n', ' ' ) ).append( '\n' );
        }
      }
      for ( String l : k.codigo ) {
        b.append( l.isEmpty() ? "" : sangria + l ).append( '\n' );
      }
      b.append( '\n' );
    }
    return b.toString();
  }

  /** «exacto», «aproximado», «a completar» en el idioma. */
  static String estado( Estado e, String i ) {
    switch ( e ) {
      case EXACTO:
        return t( i, "exacto", "exact", "exato" );
      case APROXIMADO:
        return t( i, "aproximado", "approximate", "aproximado" );
      default:
        return t( i, "a completar", "to complete", "a completar" );
    }
  }

  /** El resumen como comentario al final del .py. */
  static String resumenComentado( Programa p, Opciones o ) {
    String i = o.idioma;
    StringBuilder b = new StringBuilder( "# " ).append( t( i, "Resumen", "Summary", "Resumo" ) ).append( ": " )
      .append( cobertura( p, i ) ).append( '\n' );
    int n = 0;
    for ( Bloque k : p.bloques ) {
      n++;
      b.append( "#   " ).append( n ).append( ". " ).append( k.paso ).append( " (" ).append( k.tipo ).append( "): " )
        .append( estado( k.estado, i ) ).append( '\n' );
    }
    return b.toString();
  }

