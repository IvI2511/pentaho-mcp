  /** La explicación del bloque, o la de DescribirStep (lint) en el idioma; null si no hay ninguna. */
  static String explicacion( Programa p, Bloque k, String idioma ) {
    if ( k.explicacion != null && !k.explicacion.trim().isEmpty() ) {
      return k.explicacion.trim();
    }
    StepMeta s = p.ctx.trans == null ? null : p.ctx.trans.findStep( k.paso );
    if ( s == null ) {
      return null;
    }
    try {
      Element x = p.ctx.xml( s );
      return describir( p.ctx.trans, k.tipo, x, idioma );
    } catch ( Exception | LinkageError e ) {
      return null;
    }
  }

  /**
   * DescribirStep del lint (una línea por tipo de step, «Lee ventas.csv (8 campos)», «Filtra filas con...»). Su
   * contexto no tiene constructor público: se arma por reflexión (si falla, null).
   */
  static String describir( AbstractMeta meta, String tipo, Element x, String idioma ) throws Exception {
    io.github.ivi2511.pentahomcp.lint.Opciones op = new io.github.ivi2511.pentahomcp.lint.Opciones();
    op.lang = idioma;
    Constructor<?> k = io.github.ivi2511.pentahomcp.lint.Ctx.class.getDeclaredConstructor( AbstractMeta.class,
      io.github.ivi2511.pentahomcp.lint.Opciones.class );
    k.setAccessible( true );
    Object ctx = k.newInstance( meta, op );
    String d = io.github.ivi2511.pentahomcp.lint.DescribirStep.step( (io.github.ivi2511.pentahomcp.lint.Ctx) ctx, tipo,
      x, tipo );
    return d == null || d.trim().isEmpty() ? null : d.trim();
  }

  // ================================================================ análisis exploratorio

  /** Un DataFrame a explorar: su variable y de dónde sale. */
  static final class Explorar {
    final String df;
    final String titulo;

    Explorar( String df, String titulo ) {
      this.df = df;
      this.titulo = titulo;
    }
  }

  /** Lo que se explora: las entradas (bloques que leen) y las salidas (lo que se escribe y los steps finales). */
  static List<Explorar> aExplorar( Programa p, String i ) {
    List<Explorar> r = new ArrayList<>();
    Set<String> vistos = new LinkedHashSet<>();
    for ( Bloque k : p.bloques ) {
      if ( k.lee && k.vista != null && vistos.add( k.vista ) ) {
        r.add( new Explorar( k.vista, t( i, "Entrada «", "Input '", "Entrada «" ) + k.paso + t( i, "»", "'", "»" ) ) );
      }
    }
    for ( Bloque k : p.bloques ) {
      String v = null;
      if ( k.escribe && k.escribeDf != null ) {
        v = k.escribeDf;
      } else if ( esFinal( p, k ) ) {
        v = k.vista;
      }
      if ( v != null && vistos.add( v ) ) {
        r.add( new Explorar( v, t( i, "Salida «", "Output '", "Saída «" ) + k.paso + t( i, "»", "'", "»" ) ) );
      }
    }
    return r;
  }

  /** ¿El step del bloque no tiene siguientes (es un final del flujo)? */
  static boolean esFinal( Programa p, Bloque k ) {
    if ( p.ctx.trans == null ) {
      return false;
    }
    StepMeta s = p.ctx.trans.findStep( k.paso );
    return s != null && p.ctx.siguientes( s ).isEmpty();
  }

  /** La función eda(df, titulo) de matplotlib: forma, tipos, nulos, describe, histogramas y categorías. */
  static List<String> edaAyudante( Programa p, String i ) {
    List<String> r = new ArrayList<>();
    r.add( "import matplotlib.pyplot as plt" );
    r.add( "" );
    r.add( "" );
    r.add( "def eda(df, titulo, max_filas=10000):" );
    r.add( "    \"\"\"" + t( i, "Análisis exploratorio de un DataFrame: forma, tipos, nulos, estadísticas y gráficos.",
      "Exploratory analysis of a DataFrame: shape, types, nulls, statistics and charts.",
      "Análise exploratória de um DataFrame: forma, tipos, nulos, estatísticas e gráficos." ) + "\"\"\"" );
    if ( p.destino() == Destino.PYSPARK ) {
      r.add( "    if not isinstance(df, pd.DataFrame):  # PySpark: " + t( i, "una muestra limitada a pandas",
        "a limited sample to pandas", "uma amostra limitada para pandas" ) );
      r.add( "        df = df.limit(max_filas).toPandas()" );
    }
    r.add( "    print(f\"== {titulo}: {df.shape[0]} " + t( i, "filas", "rows", "linhas" ) + " x {df.shape[1]} "
      + t( i, "columnas", "columns", "colunas" ) + "\")" );
    r.add( "    print(pd.DataFrame({\"dtype\": df.dtypes.astype(str), \"" + t( i, "nulos", "nulls", "nulos" )
      + "\": df.isna().sum()}))" );
    r.add( "    if df.empty:" );
    r.add( "        return" );
    r.add( "    print(df.describe(include=\"all\").T)" );
    r.add( "    numericas = df.select_dtypes(include=\"number\").columns.tolist()" );
    r.add( "    if numericas:" );
    r.add( "        df[numericas].hist(bins=20, figsize=(4 * min(len(numericas), 3), 3 * ((len(numericas) + 2) // 3)),"
      + " layout=((len(numericas) + 2) // 3, min(len(numericas), 3)))" );
    r.add( "        plt.suptitle(titulo + \" - " + t( i, "distribución de las columnas numéricas",
      "distribution of numeric columns", "distribuição das colunas numéricas" ) + "\")" );
    r.add( "        plt.tight_layout()" );
    r.add( "        plt.show()" );
    r.add( "    texto = [c for c in df.columns if c not in numericas][:3]" );
    r.add( "    for c in texto:" );
    r.add( "        top = df[c].astype(str).value_counts().head(10)" );
    r.add( "        if 1 < len(top) and top.iloc[0] > 1:" );
    r.add( "            top.sort_values().plot.barh(figsize=(6, 3), title=f\"{titulo} - {c} (top 10)\")" );
    r.add( "            plt.tight_layout()" );
    r.add( "            plt.show()" );
    return r;
  }

  /** El gráfico sugerido por un bloque (Bloque.grafico) con matplotlib; null si no hay. */
  static List<String> grafico( Programa p, Bloque k, String i ) {
    Bloque.Grafico g = k.grafico;
    if ( g == null || g.df == null ) {
      return null;
    }
    List<String> r = new ArrayList<>();
    String df = g.df;
    String v = "_g";
    if ( p.destino() == Destino.PYSPARK ) {
      r.add( v + " = " + df + ".limit(10000).toPandas()" );
    } else {
      r.add( v + " = " + df );
    }
    String titulo = CtxTrad.lit( k.paso );
    if ( "histograma".equals( g.tipo ) && g.y != null ) {
      r.add( v + "[" + CtxTrad.lit( g.y ) + "].astype(float).plot.hist(bins=20, figsize=(6, 3), title=" + titulo
        + ")" );
    } else if ( "linea".equals( g.tipo ) && g.x != null && g.y != null ) {
      r.add( v + ".plot.line(x=" + CtxTrad.lit( g.x ) + ", y=" + CtxTrad.lit( g.y ) + ", figsize=(6, 3), title="
        + titulo + ")" );
    } else if ( g.x != null && g.y != null ) {
      r.add( v + ".head(20).plot.bar(x=" + CtxTrad.lit( g.x ) + ", y=" + CtxTrad.lit( g.y ) + ", figsize=(6, 3), "
        + "title=" + titulo + ")" );
    } else {
      return null;
    }
    r.add( "plt.tight_layout()" );
    r.add( "plt.show()" );
    return r;
  }

  /** La función analisis_exploratorio() del .py (apagada: hay que llamarla). */
  static List<String> edaFuncion( Programa p, Opciones o ) {
    String i = o.idioma;
    List<String> r = new ArrayList<>();
    r.add( "# " + t( i, "Análisis exploratorio (opcional): descomenta la última línea para verlo.",
      "Exploratory analysis (optional): uncomment the last line to see it.",
      "Análise exploratória (opcional): descomente a última linha para vê-la." ) );
    r.addAll( edaAyudante( p, i ) );
    r.add( "" );
    r.add( "" );
    r.add( "def analisis_exploratorio():" );
    boolean algo = false;
    for ( Explorar e : aExplorar( p, i ) ) {
      r.add( "    eda(" + e.df + ", " + CtxTrad.lit( e.titulo ) + ")" );
      algo = true;
    }
    for ( Bloque k : p.bloques ) {
      List<String> g = grafico( p, k, i );
      if ( g != null ) {
        for ( String l : g ) {
          r.add( "    " + l );
        }
        algo = true;
      }
    }
    if ( !algo ) {
      r.add( "    pass" );
    }
    r.add( "" );
    r.add( "" );
    r.add( "# analisis_exploratorio()" );
    return r;
  }

