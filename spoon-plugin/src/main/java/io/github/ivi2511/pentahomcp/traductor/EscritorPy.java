package io.github.ivi2511.pentahomcp.traductor;

import java.util.ArrayList;
import java.util.List;
import java.util.Map;

import org.pentaho.di.core.database.DatabaseMeta;

/**
 * Escribe un {@link Programa} como un script .py: cabecera (de dónde sale, estado), imports, SparkSession, VARS,
 * conexiones, funciones auxiliares y un párrafo por step con su comentario y sus notas. {@link #cuerpo} da sólo los
 * bloques (con sangría), para meter una transformación dentro de una función de un job.
 */
public final class EscritorPy {

  private EscritorPy() {
  }

  public static String escribir( Programa p ) {
    StringBuilder b = new StringBuilder();
    List<String> pre = preambulo( p );
    b.append( cabecera( p ) );
    for ( String l : pre ) {
      b.append( l ).append( '\n' );
    }
    b.append( '\n' ).append( cuerpo( p, "" ) );
    return b.toString();
  }

  /** Docstring de cabecera. */
  public static String cabecera( Programa p ) {
    CtxTrad c = p.ctx;
    StringBuilder b = new StringBuilder( "\"\"\"\n" );
    b.append( c.t( "Traducción a Python de la transformación «", "Python translation of the transformation '",
      "Tradução para Python da transformação «" ) ).append( p.nombre ).append( c.t( "»", "'", "»" ) ).append(
        " (" ).append( p.destino().id() ).append( ").\n" );
    if ( p.archivo != null ) {
      b.append( c.t( "Origen: ", "Source: ", "Origem: " ) ).append( nombreArchivo( p.archivo ) ).append( '\n' );
    }
    b.append( c.t( "Generado por Pentaho Live. Steps: ", "Generated by Pentaho Live. Steps: ",
      "Gerado pelo Pentaho Live. Steps: " ) ).append( p.bloques.size() ).append( " (" ).append( p.cuantos(
        Estado.EXACTO ) ).append( c.t( " exactos, ", " exact, ", " exatos, " ) ).append( p.cuantos(
          Estado.APROXIMADO ) ).append( c.t( " aproximados, ", " approximate, ", " aproximados, " ) ).append(
            p.cuantos( Estado.MANUAL ) ).append( c.t( " a completar)", " to complete)", " a completar)" ) ).append(
              ".\n\"\"\"\n" );
    return b.toString();
  }

  static String nombreArchivo( String f ) {
    String s = f.replace( '\\', '/' );
    return s.substring( s.lastIndexOf( '/' ) + 1 );
  }

  /** Imports, SparkSession, conexiones, VARS y ayudantes (las conexiones primero: registran variables). */
  public static List<String> preambulo( Programa p ) {
    CtxTrad c = p.ctx;
    List<String> con = new ArrayList<>();
    for ( DatabaseMeta db : new ArrayList<>( c.conexiones.values() ) ) {
      con.addAll( Conexiones.crear( db, c ) );
    }
    List<String> r = new ArrayList<>( c.imports );
    r.add( "" );
    if ( c.spark() ) {
      r.add( "_builder = SparkSession.builder.appName(" + CtxTrad.lit( p.nombre ) + ")" );
      r.add( "if os.name == \"nt\":  # " + c.t( "Windows: Spark local en localhost (un nombre de equipo con _ lo rompe)",
        "Windows: local Spark on localhost (a host name with _ breaks it)",
        "Windows: Spark local em localhost (um nome de máquina com _ o quebra)" ) );
      r.add( "    _builder = _builder.config(\"spark.driver.host\", \"localhost\").config(\"spark.driver.bindAddress\", "
        + "\"127.0.0.1\")" );
      r.add( "spark = _builder.getOrCreate()" );
      r.add( "" );
    }
    r.add( "# " + c.t( "carpeta del script (o del notebook): la misma que la del .ktr",
      "folder of the script (or notebook): the same as the .ktr's", "pasta do script (ou do notebook): a mesma do .ktr" ) );
    r.add( "AQUI = os.path.dirname(os.path.abspath(__file__)) if \"__file__\" in globals() else os.getcwd()" );
    r.add( "VARS = {" );
    for ( Map.Entry<String, String> e : c.vars.entrySet() ) {
      r.add( "    " + CtxTrad.lit( e.getKey() ) + ": " + e.getValue() + "," );
    }
    r.add( "}" );
    if ( !con.isEmpty() ) {
      r.add( "" );
      r.addAll( con );
    }
    for ( String a : c.ayudantes.values() ) {
      r.add( "" );
      r.add( "" );
      for ( String l : a.split( "\n" ) ) {
        r.add( l );
      }
    }
    return r;
  }

  /** Los bloques, cada uno con su comentario de cabecera, con la sangría dada. */
  public static String cuerpo( Programa p, String sangria ) {
    StringBuilder b = new StringBuilder();
    int i = 0;
    for ( Bloque k : p.bloques ) {
      i++;
      b.append( sangria ).append( "# --- " ).append( i ).append( ". " ).append( k.paso ).append( " (" ).append(
        k.tipo ).append( ")" ).append( k.estado == Estado.EXACTO ? "" : " · " + k.estado.id() ).append( '\n' );
      if ( k.explicacion != null ) {
        b.append( sangria ).append( "# " ).append( k.explicacion ).append( '\n' );
      }
      for ( String n : k.notas ) {
        b.append( sangria ).append( "# " ).append( p.ctx.t( "NOTA: ", "NOTE: ", "NOTA: " ) ).append( n.replace( '\n',
          ' ' ) ).append( '\n' );
      }
      for ( String l : k.codigo ) {
        b.append( l.isEmpty() ? "" : sangria + l ).append( '\n' );
      }
      b.append( '\n' );
    }
    return b.toString();
  }
}
