package io.github.ivi2511.pentahomcp.traductor;

import java.util.Arrays;
import java.util.List;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.SerializationFeature;
import com.fasterxml.jackson.databind.node.ArrayNode;
import com.fasterxml.jackson.databind.node.ObjectNode;

/**
 * Escribe un {@link Programa} como notebook de Jupyter (nbformat 4.5): título (autor, origen, fecha, cobertura),
 * introducción, cómo correrlo, el preámbulo y, por cada step, una celda de texto (qué hace, notas) y una de código (el
 * bloque y la vista previa de su DataFrame); con EDA, una sección de análisis exploratorio con matplotlib; al final, el
 * resumen (step, tipo, estado).
 */
public final class EscritorIpynb {

  private EscritorIpynb() {
  }

  /** Con las opciones por defecto (explicaciones, vistas y notas; sin EDA). */
  public static String escribir( Programa p ) throws Exception {
    Opciones o = new Opciones();
    o.idioma = p.ctx.idioma;
    o.destino = p.destino();
    return escribir( p, o );
  }

  public static String escribir( Programa p, Opciones o ) throws Exception {
    ObjectMapper om = new ObjectMapper().enable( SerializationFeature.INDENT_OUTPUT );
    ObjectNode nb = om.createObjectNode();
    ArrayNode celdas = nb.putArray( "cells" );
    String i = o.idioma;
    int[] id = { 0 };

    // título
    StringBuilder tit = new StringBuilder( "# " ).append( EscritorPy.titulo( p, o ) ).append( "\n\n" );
    if ( !EscritorPy.vacio( o.autor ) ) {
      tit.append( "**" ).append( EscritorPy.t( i, "Autor", "Author", "Autor" ) ).append( ":** " ).append( o.autor
        .trim() ).append( "  \n" );
    }
    if ( p.archivo != null ) {
      tit.append( "**" ).append( EscritorPy.t( i, "Origen", "Source", "Origem" ) ).append( ":** `" ).append(
        EscritorPy.nombreArchivo( p.archivo ) ).append( "` (" ).append( EscritorPy.t( i, "transformación de Pentaho",
          "Pentaho transformation", "transformação do Pentaho" ) ).append( ")  \n" );
    }
    tit.append( "**" ).append( EscritorPy.t( i, "Fecha", "Date", "Data" ) ).append( ":** " ).append( EscritorPy
      .hoy() ).append( "  \n" );
    tit.append( "**" ).append( EscritorPy.t( i, "Biblioteca", "Library", "Biblioteca" ) ).append( ":** " ).append(
      p.destino() == Destino.PYSPARK ? "PySpark" : "pandas" ).append( "  \n" );
    tit.append( "**" ).append( EscritorPy.t( i, "Cobertura", "Coverage", "Cobertura" ) ).append( ":** " ).append(
      EscritorPy.cobertura( p, i ) ).append( "\n\n" );
    tit.append( "*" ).append( EscritorPy.t( i, "Generado por Pentaho Live a partir de la transformación.",
      "Generated by Pentaho Live from the transformation.", "Gerado pelo Pentaho Live a partir da transformação." ) )
      .append( "*" );
    texto( celdas, id, tit.toString() );

    // introducción propia
    if ( !EscritorPy.vacio( o.introduccion ) ) {
      texto( celdas, id, o.introduccion.trim() );
    }

    // cómo correrlo
    StringBuilder como = new StringBuilder( "## " ).append( EscritorPy.t( i, "Cómo correrlo", "How to run it",
      "Como executá-lo" ) ).append( "\n\n" );
    for ( String l : EscritorPy.comoCorrer( p, o, true ) ) {
      como.append( l ).append( '\n' );
    }
    texto( celdas, id, como.toString().trim() );

    // comprobación de las bibliotecas (antes de cualquier import)
    codigo( celdas, id, String.join( "\n", Requisitos.comprobacion( EscritorPy.paquetes( p, o ), i ) ) );

    // preámbulo
    List<String> pre = EscritorPy.preambulo( p );
    String preambulo = String.join( "\n", pre ).trim();
    if ( o.eda ) {
      preambulo = preambulo + "\n\nimport matplotlib.pyplot as plt";
      if ( p.destino() == Destino.PYSPARK ) {
        preambulo = preambulo + "\nimport pandas as pd";
      }
    }
    codigo( celdas, id, preambulo );

    // un par de celdas por step
    int n = 0;
    for ( Bloque k : p.bloques ) {
      n++;
      StringBuilder t = new StringBuilder( "## " + n + ". " + k.paso + "\n\n`" + k.tipo + "`" );
      if ( k.estado != Estado.EXACTO ) {
        t.append( " · **" ).append( EscritorPy.estado( k.estado, i ) ).append( "**" );
      }
      String ex = o.explicaciones ? EscritorPy.explicacion( p, k, i ) : null;
      if ( ex != null ) {
        t.append( "\n\n" ).append( ex );
      }
      if ( o.notas || k.estado == Estado.MANUAL ) {
        for ( String x : k.notas ) {
          t.append( "\n\n> " ).append( EscritorPy.t( i, "Nota: ", "Note: ", "Nota: " ) ).append( x.replace( "\n",
            "\n> " ) );
        }
      }
      texto( celdas, id, t.toString() );
      StringBuilder cod = new StringBuilder( String.join( "\n", k.codigo ) );
      if ( o.vistas && k.vista != null ) {
        cod.append( "\n" ).append( p.ctx.pandas() ? k.vista + ".head(10)" : k.vista + ".show(10)" );
      }
      codigo( celdas, id, cod.toString() );
      if ( o.eda ) {
        List<String> g = EscritorPy.grafico( p, k, i );
        if ( g != null ) {
          codigo( celdas, id, String.join( "\n", g ) );
        }
      }
    }

    // análisis exploratorio
    if ( o.eda ) {
      List<EscritorPy.Explorar> ex = EscritorPy.aExplorar( p, i );
      texto( celdas, id, "## " + EscritorPy.t( i, "Análisis exploratorio", "Exploratory analysis",
        "Análise exploratória" ) + "\n\n" + EscritorPy.t( i, "Para cada entrada y cada salida: forma, tipos, nulos, "
          + "estadísticas, histogramas de las columnas numéricas y las categorías más frecuentes.",
          "For each input and output: shape, types, nulls, statistics, histograms of the numeric columns and the most "
            + "frequent categories.", "Para cada entrada e saída: forma, tipos, nulos, estatísticas, histogramas das "
              + "colunas numéricas e as categorias mais frequentes." ) + ( p.destino() == Destino.PYSPARK ? "\n\n"
                + EscritorPy.t( i, "Con PySpark se grafica una muestra (`limit(10000).toPandas()`).", "With PySpark a "
                  + "sample is plotted (`limit(10000).toPandas()`).", "Com PySpark é plotada uma amostra "
                    + "(`limit(10000).toPandas()`)." ) : "" ) );
      List<String> ay = EscritorPy.edaAyudante( p, i );
      codigo( celdas, id, String.join( "\n", ay.subList( 3, ay.size() ) ) ); // sin el import (está en el preámbulo)
      for ( EscritorPy.Explorar e : ex ) {
        texto( celdas, id, "### " + e.titulo );
        codigo( celdas, id, "eda(" + e.df + ", " + CtxTrad.lit( e.titulo ) + ")" );
      }
    }

    // resumen
    StringBuilder res = new StringBuilder( "## " ).append( EscritorPy.t( i, "Resumen", "Summary", "Resumo" ) )
      .append( "\n\n" ).append( EscritorPy.cobertura( p, i ) ).append( "\n\n| # | Step | " ).append( EscritorPy.t( i,
        "Tipo", "Type", "Tipo" ) ).append( " | " ).append( EscritorPy.t( i, "Estado", "Status", "Estado" ) ).append(
          " |\n|---|---|---|---|\n" );
    n = 0;
    for ( Bloque k : p.bloques ) {
      n++;
      res.append( "| " ).append( n ).append( " | " ).append( k.paso.replace( "|", "\\|" ) ).append( " | `" ).append(
        k.tipo ).append( "` | " ).append( EscritorPy.estado( k.estado, i ) ).append( " |\n" );
    }
    texto( celdas, id, res.toString().trim() );

    ObjectNode meta = nb.putObject( "metadata" );
    ObjectNode ks = meta.putObject( "kernelspec" );
    ks.put( "name", "python3" ).put( "display_name", "Python 3" ).put( "language", "python" );
    meta.putObject( "language_info" ).put( "name", "python" );
    nb.put( "nbformat", 4 ).put( "nbformat_minor", 5 );
    return om.writeValueAsString( nb );
  }

  /** Celda de texto con un id nuevo (nbformat 4.5 pide id en cada celda). */
  static void texto( ArrayNode celdas, String s ) {
    texto( celdas, new int[] { celdas.size() }, s );
  }

  /** Celda de código con un id nuevo. */
  static void codigo( ArrayNode celdas, String s ) {
    codigo( celdas, new int[] { celdas.size() }, s );
  }

  static void texto( ArrayNode celdas, int[] id, String s ) {
    ObjectNode c = celdas.addObject();
    c.put( "cell_type", "markdown" );
    c.put( "id", "c" + ( ++id[ 0 ] ) );
    c.putObject( "metadata" );
    lineas( c.putArray( "source" ), s );
  }

  static void codigo( ArrayNode celdas, int[] id, String s ) {
    ObjectNode c = celdas.addObject();
    c.put( "cell_type", "code" );
    c.put( "id", "c" + ( ++id[ 0 ] ) );
    c.putNull( "execution_count" );
    c.putObject( "metadata" );
    c.putArray( "outputs" );
    lineas( c.putArray( "source" ), s );
  }

  private static void lineas( ArrayNode a, String s ) {
    List<String> l = Arrays.asList( s.split( "\n", -1 ) );
    for ( int i = 0; i < l.size(); i++ ) {
      a.add( i < l.size() - 1 ? l.get( i ) + "\n" : l.get( i ) );
    }
  }
}
