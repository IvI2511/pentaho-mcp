  private static void conPython( Destino d ) {
    String f = Verificacion.falta( d, "es" );
    if ( f != null ) {
      Verificador.saltear( f );
    }
  }

  public void pruebaVerificaIgual() throws Exception {
    conPython( Destino.PANDAS );
    File dir = EntornoKettle.salida( "traducir-tools/igual" );
    File ktr = PruebaTraductorEscritores.ejemplo( dir );
    ObjectNode a = args( ktr, "py" );
    a.put( "verify", true ).put( "overwrite", true );
    JsonNode r = (JsonNode) TraducirTools.traducirTool( a );
    JsonNode v = r.get( "verification" );
    igual( Verificacion.IGUAL, v.get( "status" ).asText(), "PDI y Python dan lo mismo: " + v );
    igual( 6, v.get( "outputs" ).get( 0 ).get( "rows_pdi" ).asInt(), "filas de PDI" );
    igual( 6, v.get( "outputs" ).get( 0 ).get( "rows_python" ).asInt(), "filas de Python" );
  }

  public void pruebaVerificaDistintaYSinEscribir() throws Exception {
    conPython( Destino.PANDAS );
    File dir = EntornoKettle.salida( "traducir-tools/escribe" );
    File ktr = PruebaTraductorEscritores.ejemplo( dir );
    // + Text file output «Guardar» que escribiría salida.csv
    TransMeta t = new TransMeta( ktr.getAbsolutePath() );
    TextFileOutputMeta tfo = new TextFileOutputMeta();
    tfo.setDefault();
    tfo.setFileName( "${Internal.Entry.Current.Directory}/salida" );
    tfo.setExtension( "csv" );
    StepMeta g = new StepMeta( "TextFileOutput", "Guardar", tfo );
    g.setLocation( 500, 100 );
    t.addStep( g );
    t.addTransHop( new TransHopMeta( t.findStep( "Resultado" ), g ) );
    Files.write( ktr.toPath(), t.getXML().getBytes( StandardCharsets.UTF_8 ) );
    File salida = new File( dir, "salida.csv" );
    salida.delete();
    TraductorStep antes = Registro.buscar( "TextFileOutput" );
    Registro.step( ( s, ctx ) -> {
      Bloque b = new Bloque( s.getName(), s.getStepID() );
      String in = ctx.entradaUnida( s, b );
      b.l( in + ".to_csv(os.path.join(AQUI, \"salida.csv\"), index=False)" );
      b.l( ctx.df( s ) + " = " + in );
      b.escribe = true;
      b.escribeDf = in;
      return b;
    }, "TextFileOutput" );
    try {
      TransMeta t2 = new TransMeta( ktr.getAbsolutePath() );
      Programa p = TraductorTrans.traducir( t2, Destino.PANDAS, "es" );
      Verificacion.Resultado r = TraducirTools.verificar( p, t2.getXML(), ktr, opcionesEs() );
      igual( Verificacion.IGUAL, r.estado, "igual con el step que escribe saltado: " + TraducirTools.json( r ) );
      igual( 1, r.salidas.size(), "una salida: lo que escribe Guardar" );
      igual( "Guardar", r.salidas.get( 0 ).paso, "la salida es Guardar" );
      cierto( !salida.exists(), "ni PDI ni Python escribieron salida.csv" );
      // ahora Python pierde una fila: distinta, con las diferencias
      for ( Bloque b : p.bloques ) {
        if ( "Resultado".equals( b.paso ) ) {
          b.l( "df_resultado = df_resultado.iloc[1:]" );
        }
      }
      Verificacion.Resultado d = TraducirTools.verificar( p, t2.getXML(), ktr, opcionesEs() );
      igual( Verificacion.DISTINTO, d.estado, "distinta: " + TraducirTools.json( d ) );
      Verificacion.Salida s = d.salidas.get( 0 );
      igual( 6, s.filasPdi, "PDI 6" );
      igual( 5, s.filasPython, "Python 5" );
      cierto( !s.diferencias.isEmpty(), "con diferencias" );
      cierto( !salida.exists(), "sigue sin escribir" );
    } finally {
      if ( antes != null ) {
        Registro.step( antes, "TextFileOutput" );
      }
    }
  }

  private static Opciones opcionesEs() {
    Opciones o = new Opciones();
    o.idioma = "es";
    return o;
  }

  public void pruebaSinPython() throws Exception {
    String antes = System.getProperty( "pentaho.live.python" );
    System.setProperty( "pentaho.live.python", "no-existe-este-python-xyz" );
    Verificacion.olvidarPython();
    try {
      File dir = EntornoKettle.salida( "traducir-tools/sinpy" );
      File ktr = PruebaTraductorEscritores.ejemplo( dir );
      TransMeta t = new TransMeta( ktr.getAbsolutePath() );
      Programa p = TraductorTrans.traducir( t, Destino.PANDAS, "en" );
      Opciones o = opcionesEs();
      o.idioma = "en";
      Verificacion.Resultado r = TraducirTools.verificar( p, t.getXML(), ktr, o );
      igual( Verificacion.SIN_VERIFICAR, r.estado, "sin Python: no verificada" );
      contiene( r.motivo, "PENTAHO_LIVE_PYTHON", "dice cómo indicar Python" );
      contiene( r.salidas.get( 0 ).motivo, "No Python", "cada salida dice por qué" );
    } finally {
      if ( antes == null ) {
        System.clearProperty( "pentaho.live.python" );
      } else {
        System.setProperty( "pentaho.live.python", antes );
      }
      Verificacion.olvidarPython();
    }
  }

  public void pruebaVerificaPySpark() throws Exception {
    conPython( Destino.PYSPARK );
    File dir = EntornoKettle.salida( "traducir-tools/pyspark" );
    File ktr = PruebaTraductorEscritores.ejemplo( dir );
    TransMeta t = new TransMeta( ktr.getAbsolutePath() );
    Programa p = TraductorTrans.traducir( t, Destino.PYSPARK, "es" );
    Verificacion.Resultado r = TraducirTools.verificar( p, t.getXML(), ktr, opcionesEs() );
    igual( Verificacion.IGUAL, r.estado, "PySpark igual que PDI: " + TraducirTools.json( r ) );
  }
